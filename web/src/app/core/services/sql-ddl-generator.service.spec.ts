import { describe, it, expect, beforeEach } from 'vitest';
import { SqlDdlGeneratorService } from './sql-ddl-generator.service';
import { UmlClassNode, UmlConnection } from '../models/diagram.model';

describe('SqlDdlGeneratorService', () => {
  let service: SqlDdlGeneratorService;

  beforeEach(() => {
    service = new SqlDdlGeneratorService();
  });

  it('debe generar CREATE TYPE ENUM, tablas con PK simple/compuesta, FK 1:N, tabla M:N y omitir INTERFACE/NOTE', () => {
    const nodes: UmlClassNode[] = [
      {
        id: 'e1',
        name: 'EstadoPedido',
        elementType: 'ENUM',
        position: { x: 0, y: 0 },
        width: 220,
        attributes: [
          { name: 'PENDIENTE', type: 'EnumLiteral', visibility: '+' },
          { name: 'PAGADO', type: 'EnumLiteral', visibility: '+' },
        ],
        methods: [],
      },
      {
        id: 'n1',
        name: 'Cliente',
        elementType: 'CLASS',
        position: { x: 100, y: 100 },
        width: 220,
        attributes: [
          { name: 'clienteId', type: 'Long', isPrimaryKey: true, isNullable: false, visibility: '-' },
          { name: 'email', type: 'String', isNullable: false, visibility: '-' },
        ],
        methods: [],
      },
      {
        id: 'n2',
        name: 'Pedido',
        elementType: 'CLASS',
        position: { x: 400, y: 100 },
        width: 220,
        attributes: [
          { name: 'id', type: 'UUID', isPrimaryKey: true, isNullable: false },
          { name: 'estado', type: 'EstadoPedido', isNullable: false },
        ],
        methods: [],
      },
      {
        id: 'n3',
        name: 'Etiqueta',
        elementType: 'CLASS',
        position: { x: 700, y: 100 },
        width: 220,
        attributes: [
          { name: 'tenantId', type: 'UUID', isPrimaryKey: true, isNullable: false },
          { name: 'codigo', type: 'String', isPrimaryKey: true, isNullable: false },
        ],
        methods: [],
      },
      {
        id: 'n_if',
        name: 'INotificador',
        elementType: 'INTERFACE',
        position: { x: 100, y: 350 },
        width: 220,
        attributes: [],
        methods: [],
      },
      {
        id: 'n_note',
        name: 'Nota_1',
        elementType: 'NOTE',
        noteContent: 'Regla',
        position: { x: 400, y: 350 },
        width: 220,
        attributes: [],
        methods: [],
      },
    ];

    const connections: UmlConnection[] = [
      {
        id: 'c1',
        sourceNodeId: 'n1',
        targetNodeId: 'n2',
        sourceId: 'n1_right',
        targetId: 'n2_left',
        type: 'association',
        sourceMultiplicity: '1',
        targetMultiplicity: '1..*',
      },
      {
        id: 'c2',
        sourceNodeId: 'n2',
        targetNodeId: 'n3',
        sourceId: 'n2_right',
        targetId: 'n3_left',
        type: 'association',
        sourceMultiplicity: '*',
        targetMultiplicity: '*',
      },
    ];

    const ddl = service.generatePostgreSqlDdl(nodes, connections, {
      diagramName: 'Ventas Test',
      includeDropStatements: true,
      includeForeignKeyIndexes: true,
      includeTransactionWrapper: true,
    });

    expect(ddl).toContain('BEGIN;');
    expect(ddl).toContain('COMMIT;');
    expect(ddl).toContain('DROP TABLE IF EXISTS "cliente" CASCADE;');
    expect(ddl).toContain('CREATE TYPE "estado_pedido_enum" AS ENUM (\'PENDIENTE\', \'PAGADO\');');
    expect(ddl).toContain('"cliente_id" BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY');
    expect(ddl).toContain('"email" VARCHAR(255) NOT NULL');
    expect(ddl).toContain('"estado" "estado_pedido_enum" NOT NULL');
    expect(ddl).toContain('CONSTRAINT "pk_etiqueta" PRIMARY KEY ("tenant_id", "codigo")');
    expect(ddl).toContain('CREATE TABLE IF NOT EXISTS "pedido_etiqueta"');
    expect(ddl).toContain('FOREIGN KEY ("cliente_id")');
    expect(ddl).toContain('REFERENCES "cliente" ("cliente_id")');
    expect(ddl).toContain('CREATE INDEX IF NOT EXISTS "idx_pedido_cliente_id"');
    expect(ddl).not.toContain('i_notificador');
    expect(ddl).not.toContain('nota_1');
  });
});

