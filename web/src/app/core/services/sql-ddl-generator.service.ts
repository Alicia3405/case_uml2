import { Injectable } from '@angular/core';
import { UmlAttribute, UmlClassNode, UmlConnection } from '../models/diagram.model';

export interface SqlDdlOptions {
  diagramName?: string;
  includeDropStatements?: boolean;
  includeForeignKeyIndexes?: boolean;
  includeTransactionWrapper?: boolean;
}

interface ParsedTable {
  nodeId: string;
  className: string;
  tableName: string;
  isAssociationClass: boolean;
  assocMainConnId?: string;
  columns: ParsedColumn[];
  primaryKeyColumns: string[];
  pkSqlType: string;
  primaryPkColName: string;
}

interface ParsedColumn {
  colName: string;
  sqlType: string;
  isPk: boolean;
  isNullable: boolean;
  isDefaultGenerated: boolean;
  defaultClause?: string;
}

interface ForeignKeyConstraint {
  fromTable: string;
  fromCol: string;
  toTable: string;
  toCol: string;
  onDelete: 'CASCADE' | 'SET NULL' | 'RESTRICT';
}

@Injectable({
  providedIn: 'root',
})
export class SqlDdlGeneratorService {
  /**
   * Genera un script SQL DDL completo para PostgreSQL 16+ directamente desde el AST vivo del editor.
   */
  generatePostgreSqlDdl(
    nodes: UmlClassNode[],
    connections: UmlConnection[],
    options: SqlDdlOptions = {},
  ): string {
    const diagramTitle = options.diagramName || 'Diagrama UML';
    const includeDrops = options.includeDropStatements ?? false;
    const includeIndexes = options.includeForeignKeyIndexes ?? true;
    const includeTx = options.includeTransactionWrapper ?? false;

    const visibleNodes = (nodes || []).filter((n) => !n.isAnchor && (n.name || '').trim().length > 0);
    const enumNodes = visibleNodes.filter((n) => (n.elementType || 'CLASS').toUpperCase() === 'ENUM');
    const entityNodes = visibleNodes.filter((n) => {
      const et = (n.elementType || 'CLASS').toUpperCase();
      return et === 'CLASS' || et === 'ASSOCIATION_CLASS';
    });

    if (entityNodes.length === 0 && enumNodes.length === 0) {
      return '-- Agrega al menos una Clase o Enumeración UML al lienzo para generar el script PostgreSQL DDL.';
    }

    // Mapeo de nombres de ENUM UML -> tipo ENUM PostgreSQL
    const enumTypeMap = new Map<string, string>();
    const enumSqlStatements: string[] = [];

    for (const enumNode of enumNodes) {
      const pgEnumName = `${this.toSnakeCase(enumNode.name)}_enum`;
      const literals = (enumNode.attributes || [])
        .map((a) => (a.name || '').trim())
        .filter((v) => v.length > 0);
      if (literals.length > 0) {
        enumTypeMap.set(enumNode.name.trim().toLowerCase(), `"${pgEnumName}"`);
        const escaped = literals.map((l) => `'${l.replace(/'/g, "''")}'`).join(', ');
        enumSqlStatements.push(
          `DO $$ BEGIN\n    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = '${pgEnumName}') THEN\n        CREATE TYPE "${pgEnumName}" AS ENUM (${escaped});\n    END IF;\nEND $$;`,
        );
      }
    }

    // 1. Construir tablas base
    const tables: ParsedTable[] = [];
    const tableByNodeId = new Map<string, ParsedTable>();

    for (const node of entityNodes) {
      const tableName = this.toSnakeCase(node.name);
      const rawAttrs = node.attributes || [];
      const hasExplicitPk = rawAttrs.some((a) => Boolean(a.isPrimaryKey));
      let heuristicPkUsed = false;

      const cols: ParsedColumn[] = [];
      const seenColNames = new Set<string>();
      const pkCols: string[] = [];

      for (const attr of rawAttrs) {
        const colName = this.toSnakeCase(attr.name || 'campo');
        if (seenColNames.has(colName)) continue;
        seenColNames.add(colName);

        const isCandidate = this.isPkNameCandidate(attr.name || '', tableName);
        const isPk = hasExplicitPk ? Boolean(attr.isPrimaryKey) : !heuristicPkUsed && isCandidate;
        if (isPk && !hasExplicitPk) heuristicPkUsed = true;

        const sqlType = this.mapAttributeToSqlType(attr, enumTypeMap);
        const isNullable = isPk ? false : (attr.isNullable ?? true);
        const isDefaultGenerated = isPk && (!hasExplicitPk || pkCols.length === 0) && rawAttrs.filter((a) => a.isPrimaryKey).length <= 1;

        let defaultClause: string | undefined;
        if (isDefaultGenerated) {
          if (sqlType === 'UUID') defaultClause = 'DEFAULT gen_random_uuid()';
          else if (sqlType === 'BIGINT' || sqlType === 'INTEGER') defaultClause = 'GENERATED BY DEFAULT AS IDENTITY';
        }

        if (isPk) pkCols.push(colName);

        cols.push({
          colName,
          sqlType,
          isPk,
          isNullable,
          isDefaultGenerated,
          defaultClause,
        });
      }

      // Sintetizar ID solo si no se declaró ninguna PK explícita ni candidata
      if (pkCols.length === 0) {
        pkCols.push('id');
        cols.unshift({
          colName: 'id',
          sqlType: 'UUID',
          isPk: true,
          isNullable: false,
          isDefaultGenerated: true,
          defaultClause: 'DEFAULT gen_random_uuid()',
        });
      }

      const firstPkCol = cols.find((c) => c.colName === pkCols[0]) || cols[0];
      const parsed: ParsedTable = {
        nodeId: node.id,
        className: node.name,
        tableName,
        isAssociationClass: (node.elementType || '').toUpperCase() === 'ASSOCIATION_CLASS' || Boolean(node.assocMainConnId),
        assocMainConnId: node.assocMainConnId,
        columns: cols,
        primaryKeyColumns: pkCols,
        pkSqlType: firstPkCol?.sqlType || 'UUID',
        primaryPkColName: firstPkCol?.colName || 'id',
      };

      tables.push(parsed);
      tableByNodeId.set(node.id, parsed);
    }

    // 2. Analizar relaciones para columnas FK, tablas de unión M:N y constraints
    const fkConstraints: ForeignKeyConstraint[] = [];
    const addedFkPairs = new Set<string>();
    const joinTablesSql: string[] = [];
    const createdJoinTableNames = new Set<string>();

    for (const conn of connections || []) {
      const sourceBaseId = conn.sourceNodeId || conn.sourceId?.replace(/_(top|bottom|left|right)$/, '');
      const targetBaseId = conn.targetNodeId || conn.targetId?.replace(/_(top|bottom|left|right)$/, '');
      const srcTable = tableByNodeId.get(sourceBaseId);
      const tgtTable = tableByNodeId.get(targetBaseId);

      if (!srcTable || !tgtTable || srcTable.nodeId === tgtTable.nodeId) continue;

      const relType = (conn.type || 'association').toLowerCase();
      if (relType === 'dependency' || relType === 'realization' || relType === 'association_class') {
        continue;
      }

      if (relType === 'generalization') {
        // Herencia: tabla hija referencia a tabla padre con FK NOT NULL
        this.attachForeignKey(srcTable, tgtTable, fkConstraints, addedFkPairs, 'CASCADE');
        continue;
      }

      const sMult = (conn.sourceMultiplicity || '1').trim().toLowerCase();
      const tMult = (conn.targetMultiplicity || '1..*').trim().toLowerCase();
      const sourceIsMany = sMult.includes('*') || sMult.includes('n') || sMult.includes('m');
      const targetIsMany = tMult.includes('*') || tMult.includes('n') || tMult.includes('m');

      if (sourceIsMany && targetIsMany) {
        // Si ya existe una tabla asociativa vinculada (assocMainConnId === conn.id), añadirle las 2 FKs
        const linkedAssocTable = tables.find(
          (t) => t.assocMainConnId === conn.id || (conn.assocAnchorNodeId && t.isAssociationClass && t.tableName === `${srcTable.tableName}_${tgtTable.tableName}`),
        );
        if (linkedAssocTable) {
          this.attachForeignKey(linkedAssocTable, srcTable, fkConstraints, addedFkPairs, 'CASCADE');
          this.attachForeignKey(linkedAssocTable, tgtTable, fkConstraints, addedFkPairs, 'CASCADE');
        } else {
          // Generar tabla de unión PostgreSQL si es una relación M:N directa
          const joinTableName = `${srcTable.tableName}_${tgtTable.tableName}`;
          if (!createdJoinTableNames.has(joinTableName)) {
            createdJoinTableNames.add(joinTableName);
            const fk1 = `${this.toSingular(srcTable.tableName)}_id`;
            const fk2 = `${this.toSingular(tgtTable.tableName)}_id`;
            joinTablesSql.push(
              `CREATE TABLE IF NOT EXISTS "${joinTableName}" (\n` +
                `    "${fk1}" ${srcTable.pkSqlType} NOT NULL REFERENCES "${srcTable.tableName}" ("${srcTable.primaryPkColName}") ON DELETE CASCADE,\n` +
                `    "${fk2}" ${tgtTable.pkSqlType} NOT NULL REFERENCES "${tgtTable.tableName}" ("${tgtTable.primaryPkColName}") ON DELETE CASCADE,\n` +
                `    CONSTRAINT "pk_${joinTableName}" PRIMARY KEY ("${fk1}", "${fk2}")\n` +
                `);`,
            );
          }
        }
      } else if (targetIsMany && !sourceIsMany) {
        // 1:N -> FK en target
        this.attachForeignKey(tgtTable, srcTable, fkConstraints, addedFkPairs, relType === 'composition' ? 'CASCADE' : 'SET NULL');
      } else if (sourceIsMany && !targetIsMany) {
        // N:1 -> FK en source
        this.attachForeignKey(srcTable, tgtTable, fkConstraints, addedFkPairs, relType === 'composition' ? 'CASCADE' : 'SET NULL');
      } else {
        // 1:1 -> FK en target (o source si ya posee la columna)
        const srcHasRef = srcTable.columns.some((c) => c.colName === `${this.toSingular(tgtTable.tableName)}_id`);
        if (srcHasRef) {
          this.attachForeignKey(srcTable, tgtTable, fkConstraints, addedFkPairs, 'SET NULL');
        } else {
          this.attachForeignKey(tgtTable, srcTable, fkConstraints, addedFkPairs, 'SET NULL');
        }
      }
    }

    // 3. Ensamblar el script SQL DDL
    const sections: string[] = [];
    sections.push(
      `-- =============================================================================\n` +
        `-- Script SQL DDL (PostgreSQL 16+) — ${diagramTitle}\n` +
        `-- Generado automáticamente por CASE Studio AI\n` +
        `-- =============================================================================\n\n` +
        `CREATE EXTENSION IF NOT EXISTS "pgcrypto";`,
    );

    if (includeTx) {
      sections.push('BEGIN;');
    }

    if (includeDrops) {
      const drops: string[] = [];
      for (const jt of [...createdJoinTableNames].reverse()) {
        drops.push(`DROP TABLE IF EXISTS "${jt}" CASCADE;`);
      }
      for (const t of [...tables].reverse()) {
        drops.push(`DROP TABLE IF EXISTS "${t.tableName}" CASCADE;`);
      }
      for (const e of enumNodes) {
        drops.push(`DROP TYPE IF EXISTS "${this.toSnakeCase(e.name)}_enum" CASCADE;`);
      }
      if (drops.length > 0) {
        sections.push(`-- Limpieza previa\n${drops.join('\n')}`);
      }
    }

    if (enumSqlStatements.length > 0) {
      sections.push(`-- 1. Tipos Enumerados\n${enumSqlStatements.join('\n\n')}`);
    }

    if (tables.length > 0) {
      const createTablesSql = tables.map((t) => {
        const isCompositePk = t.primaryKeyColumns.length > 1;
        const colLines = t.columns.map((c) => {
          const parts: string[] = [`    "${c.colName}" ${c.sqlType}`];
          if (c.isPk && !isCompositePk) {
            parts.push('PRIMARY KEY');
            if (c.defaultClause) parts.push(c.defaultClause);
          } else if (!c.isNullable || c.isPk) {
            parts.push('NOT NULL');
          }
          return parts.join(' ');
        });

        if (isCompositePk) {
          const pkList = t.primaryKeyColumns.map((pk) => `"${pk}"`).join(', ');
          colLines.push(`    CONSTRAINT "pk_${t.tableName}" PRIMARY KEY (${pkList})`);
        }

        return `CREATE TABLE IF NOT EXISTS "${t.tableName}" (\n${colLines.join(',\n')}\n);`;
      });

      sections.push(`-- ${enumSqlStatements.length > 0 ? '2' : '1'}. Tablas de Entidades\n${createTablesSql.join('\n\n')}`);
    }

    if (joinTablesSql.length > 0) {
      sections.push(`-- Tablas de Unión (Relaciones N:M)\n${joinTablesSql.join('\n\n')}`);
    }

    if (fkConstraints.length > 0) {
      const fkLines = fkConstraints.map((fk) => {
        const constraintName = `fk_${fk.fromTable}_${fk.fromCol}`.slice(0, 63);
        return (
          `DO $$ BEGIN\n` +
          `    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${constraintName}') THEN\n` +
          `        ALTER TABLE "${fk.fromTable}"\n` +
          `            ADD CONSTRAINT "${constraintName}"\n` +
          `            FOREIGN KEY ("${fk.fromCol}")\n` +
          `            REFERENCES "${fk.toTable}" ("${fk.toCol}")\n` +
          `            ON DELETE ${fk.onDelete};\n` +
          `    END IF;\n` +
          `END $$;`
        );
      });
      sections.push(`-- Integridad Referencial (Foreign Keys)\n${fkLines.join('\n\n')}`);
    }

    if (includeIndexes && fkConstraints.length > 0) {
      const idxLines = fkConstraints.map((fk) => {
        const idxName = `idx_${fk.fromTable}_${fk.fromCol}`.slice(0, 63);
        return `CREATE INDEX IF NOT EXISTS "${idxName}" ON "${fk.fromTable}" ("${fk.fromCol}");`;
      });
      sections.push(`-- Índices de Clave Foránea\n${idxLines.join('\n')}`);
    }

    if (includeTx) {
      sections.push('COMMIT;');
    }

    return sections.join('\n\n') + '\n';
  }

  private attachForeignKey(
    childTable: ParsedTable,
    parentTable: ParsedTable,
    fkConstraints: ForeignKeyConstraint[],
    addedFkPairs: Set<string>,
    onDelete: 'CASCADE' | 'SET NULL' | 'RESTRICT',
  ): void {
    const singularParent = this.toSingular(parentTable.tableName);
    const matchingExisting = childTable.columns.find(
      (c) =>
        c.colName === `${singularParent}_id` ||
        c.colName === `${parentTable.tableName}_id` ||
        c.colName === `id_${singularParent}`,
    );

    const fkColName = matchingExisting ? matchingExisting.colName : `${singularParent}_id`;
    if (!matchingExisting) {
      childTable.columns.push({
        colName: fkColName,
        sqlType: parentTable.pkSqlType,
        isPk: false,
        isNullable: onDelete === 'SET NULL',
        isDefaultGenerated: false,
      });
    }

    const pairKey = `${childTable.tableName}.${fkColName}->${parentTable.tableName}`;
    if (!addedFkPairs.has(pairKey)) {
      addedFkPairs.add(pairKey);
      fkConstraints.push({
        fromTable: childTable.tableName,
        fromCol: fkColName,
        toTable: parentTable.tableName,
        toCol: parentTable.primaryPkColName,
        onDelete,
      });
    }
  }

  private isPkNameCandidate(rawName: string, tableName: string): boolean {
    const lower = rawName.toLowerCase().trim();
    const singular = this.toSingular(tableName);
    return (
      lower === 'id' ||
      lower === `${tableName}_id` ||
      lower === `id_${tableName}` ||
      lower === `${singular}_id` ||
      lower === `id_${singular}` ||
      this.toSnakeCase(rawName) === 'id' ||
      this.toSnakeCase(rawName) === `${singular}_id`
    );
  }

  private mapAttributeToSqlType(attr: UmlAttribute, enumTypeMap: Map<string, string>): string {
    const rawType = (attr.type || 'String').trim();
    const enumSql = enumTypeMap.get(rawType.toLowerCase());
    if (enumSql) return enumSql;

    switch (rawType.toLowerCase()) {
      case 'uuid':
        return 'UUID';
      case 'text':
        return 'TEXT';
      case 'string':
      case 'varchar':
        return 'VARCHAR(255)';
      case 'int':
      case 'integer':
        return 'INTEGER';
      case 'long':
      case 'bigint':
        return 'BIGINT';
      case 'boolean':
      case 'bool':
        return 'BOOLEAN';
      case 'double':
        return 'DOUBLE PRECISION';
      case 'float':
        return 'REAL';
      case 'bigdecimal':
      case 'decimal':
      case 'numeric':
        return 'NUMERIC(15, 2)';
      case 'localdate':
      case 'date':
        return 'DATE';
      case 'localdatetime':
      case 'timestamp':
        return 'TIMESTAMP';
      case 'byte[]':
        return 'BYTEA';
      default:
        return 'VARCHAR(255)';
    }
  }

  private toSnakeCase(str: string): string {
    return (str || 'tabla')
      .trim()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
      .replace(/[^a-zA-Z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '')
      .toLowerCase() || 'tabla';
  }

  private toSingular(str: string): string {
    if (!str) return str;
    if (str.endsWith('ies')) return str.slice(0, -3) + 'y';
    if (str.endsWith('es') && str.length > 3) return str.slice(0, -2);
    if (str.endsWith('s') && str.length > 2 && !str.endsWith('ss')) return str.slice(0, -1);
    return str;
  }
}

